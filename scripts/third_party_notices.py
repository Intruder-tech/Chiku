"""Generate THIRD_PARTY_NOTICES.md from the installed runtime dependency tree.

Walks chiku's requirements recursively with importlib.metadata (what actually ships in the
installer), and adds the models and external tools that are downloaded separately.
Run:  python scripts/third_party_notices.py   (in the project venv)
"""

from __future__ import annotations

import re
from importlib import metadata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SKIP_EXTRAS = re.compile(r"extra\s*==")

MODELS = [
    ("Kokoro-82M (voice model + voices)", "Apache-2.0", "hexgrad/Kokoro-82M; ONNX export by "
     "thewh1teagle/kokoro-onnx", "downloaded on first run"),
    ("Whisper small.en / base.en / tiny.en (CTranslate2)", "MIT", "OpenAI Whisper; conversion "
     "by Systran/faster-whisper", "downloaded on first run"),
    ("Silero VAD v5", "MIT", "snakers4/silero-vad", "downloaded on first run"),
    ("espeak-ng (phonemizer library + data, via espeakng-loader)", "GPL-3.0-or-later",
     "espeak-ng project", "bundled in the installer"),
    ("Qwen3-4B-Instruct-2507 / Llama 3.2 (language models)", "Apache-2.0 / Llama 3.2 Community "
     "License", "via Ollama", "downloaded by Ollama on request"),
    ("Ollama", "MIT", "ollama/ollama", "installed separately by the user"),
    ("NVIDIA cuBLAS / cuDNN (optional speech pack)", "NVIDIA proprietary (redistributable)",
     "PyPI nvidia-cublas-cu12 / nvidia-cudnn-cu12", "optional download, NVIDIA PCs only"),
]


def license_of(dist: metadata.Distribution) -> str:
    md = dist.metadata
    lic = md.get("License-Expression") or ""
    if not lic:
        raw = (md.get("License") or "").strip()
        lic = raw.splitlines()[0][:60] if raw and len(raw) < 200 else ""
    if not lic:
        cls = [c.split("::")[-1].strip() for c in md.get_all("Classifier") or []
               if c.startswith("License ::")]
        lic = ", ".join(cls)
    if not lic:  # fall back to the first line of a bundled licence file
        for f in dist.files or []:
            if "licen" in f.name.lower() or f.name.upper().startswith("COPYING"):
                try:
                    first = Path(str(dist.locate_file(f))).read_text(encoding="utf-8").strip()
                    lic = first.splitlines()[0][:60] + " (from licence file)"
                    break
                except (OSError, UnicodeDecodeError, IndexError):
                    continue
    return lic or NOT_DECLARED.get(dist.metadata["Name"], "not declared by the package")


NOT_DECLARED = {
    "espeakng-loader": "not declared by the package; it bundles espeak-ng (GPL-3.0-or-later)",
}


def walk(name: str, seen: dict[str, metadata.Distribution]) -> None:
    key = re.sub(r"[-_.]+", "-", name).lower()
    if key in seen:
        return
    try:
        dist = metadata.distribution(name)
    except metadata.PackageNotFoundError:
        return
    seen[key] = dist
    for req in dist.requires or []:
        if SKIP_EXTRAS.search(req) or "sys_platform != \"win32\"" in req:
            continue
        dep = re.split(r"[ ;<>=!~\[(]", req, maxsplit=1)[0]
        walk(dep, seen)


def main() -> None:
    seen: dict[str, metadata.Distribution] = {}
    walk("chiku", seen)
    seen.pop("chiku", None)
    rows = sorted((d.metadata["Name"], d.version, license_of(d)) for d in seen.values())
    out = [
        "# Third-party notices", "",
        "Chiku is licensed under GPL-3.0-or-later (see LICENSE). It includes or downloads the "
        "following third-party components, each under its own licence. The Chiku mascot "
        "artwork is **not** covered by the GPL; see assets/branding/LICENSE.md.", "",
        "## Python packages shipped in the installer", "",
        "Generated by `scripts/third_party_notices.py` from the installed dependency tree.", "",
        "| Package | Version | Licence |", "|---|---|---|",
        *(f"| {n} | {v} | {lic} |" for n, v, lic in rows), "",
        "## Models and external components", "",
        "| Component | Licence | Source | How it gets onto your PC |", "|---|---|---|---|",
        *(f"| {a} | {b} | {c} | {d} |" for a, b, c, d in MODELS), "",
        "## Notes", "",
        "- espeak-ng and phonemizer-fork are GPL-3.0; that is one reason Chiku itself is "
        "GPL-3.0-or-later, so the installer as a whole is GPL-compatible.",
        "- PySide6 / Qt are used under the LGPL-3.0 and are dynamically linked.",
        "- Full licence texts are available from each project and in the installed packages' "
        "metadata.",
    ]
    (ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rows)} packages written to THIRD_PARTY_NOTICES.md")


if __name__ == "__main__":
    main()
